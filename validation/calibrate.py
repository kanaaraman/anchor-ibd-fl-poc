"""Fit the generator's per (diagnosis, drug) offsets to the remission targets.

For every target with metric response_rate, find the logit offset for its
diagnosis x drug cell so that the expected remission rate in the target's
subgroup equals the published figure. Writes ibdfl/calibration.json.

    python validation/calibrate.py
"""
import json
import os
import sys
from datetime import date

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from ibdfl.synth import SITES, sample_patients  # noqa: E402

N_PER_SITE = 200_000
targets = json.load(open(os.path.join(ROOT, "validation", "targets.json"), encoding="utf-8"))["targets"]

# one large pooled population, equal weight per site (as validate.py measures it)
pops = [sample_patients(s, np.random.default_rng(42 + i), N_PER_SITE, offsets={}) for i, s in enumerate(SITES)]
pop = {k: np.concatenate([p[k] for p in pops]) for k in ("cd", "drug", "prior_tnf", "logit_base", "cell")}

offsets, report = {}, []
for t in targets:
    if t["metric"] != "response_rate":
        continue
    g = t["subgroup"]
    cell = f"{g['dx']}:{g['drug']}"
    if cell in offsets:
        raise SystemExit(f"two response targets for cell {cell}; keep one")
    m = (pop["cell"] == cell) & (pop["prior_tnf"] == bool(g["prior_anti_tnf"]))
    z = pop["logit_base"][m]
    lo, hi = -6.0, 6.0
    for _ in range(60):  # bisection on the expected rate
        mid = (lo + hi) / 2
        rate = float(np.mean(1 / (1 + np.exp(-(z + mid)))))
        lo, hi = (mid, hi) if rate < t["target"] else (lo, mid)
    offsets[cell] = round((lo + hi) / 2, 4)
    report.append(f"{cell:22s} {t['status']:11s} target {t['target']:.3f}  offset {offsets[cell]:+.3f}  (n={m.sum():,})")

out = {"fitted": str(date.today()), "n_per_site": N_PER_SITE,
       "note": "Logit offsets per diagnosis:drug cell. Generated by validation/calibrate.py from validation/targets.json.",
       "offsets": offsets}
with open(os.path.join(ROOT, "ibdfl", "calibration.json"), "w", encoding="utf-8") as f:
    json.dump(out, f, indent=2)
print("\n".join(report))
print(f"wrote ibdfl/calibration.json ({len(offsets)} cells)")
