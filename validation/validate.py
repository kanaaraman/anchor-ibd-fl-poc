"""Check the generated OMOP data against published figures.

Reads every site's OMOP extract (data/ and, if present, data_eval/) through the
same feature code the model uses, computes each target in
validation/targets.json and writes validation/report.md.

    python validation/validate.py            # exit code 1 if a verified target fails
"""
import json
import os
import sys

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from ibdfl.features import FEATURES, load_site  # noqa: E402
from ibdfl.vocab import DRUG_ORDER  # noqa: E402

col = {f: i for i, f in enumerate(FEATURES)}
targets = json.load(open(os.path.join(ROOT, "validation", "targets.json"), encoding="utf-8"))["targets"]


def load(site):
    parts = [load_site(os.path.join(ROOT, d, site)) for d in ("data", "data_eval") if os.path.isdir(os.path.join(ROOT, d, site))]
    X = np.concatenate([p[0] for p in parts]); y = np.concatenate([p[1] for p in parts]); drug = np.concatenate([p[3] for p in parts])
    return X, y, drug


cache = {}


def measure(t):
    Xs, ys, ds = zip(*[cache.setdefault(s, load(s)) for s in t["sites"]])
    X, y, drug = np.concatenate(Xs), np.concatenate(ys), np.concatenate(ds)
    m = np.ones(len(y), bool)
    g = t["subgroup"]
    if "dx" in g:
        m &= X[:, col["crohns"]] == (1.0 if g["dx"] == "CD" else 0.0)
    if "drug" in g:
        m &= drug == DRUG_ORDER.index(g["drug"])
    if "prior_anti_tnf" in g:
        m &= X[:, col["prior_anti_tnf"]] == float(g["prior_anti_tnf"])
    metric = {"share_cd": X[m, col["crohns"]], "share_female": X[m, col["female"]],
              "share_smoker": X[m, col["smoker"]], "response_rate": y[m]}[t["metric"]]
    v = float(metric.mean())
    se = float(np.sqrt(v * (1 - v) / max(1, m.sum())))
    return v, se, int(m.sum())


rows, failed = [], []
for t in targets:
    v, se, n = measure(t)
    diff = v - t["target"]
    if t["status"] == "assumption":
        verdict = "not scored"
    else:
        verdict = "pass" if abs(diff) <= t["tolerance"] else "FAIL"
        if verdict == "FAIL" and t["status"] == "verified":
            failed.append(t["id"])
    rows.append((t, v, se, n, diff, verdict))
    print(f"{verdict:10s} {t['status']:11s} {t['id']:20s} synthetic {v:.3f} ±{1.96 * se:.3f} (n={n:,})  target {t['target']:.3f} ±{t['tolerance']:.3f}")

with open(os.path.join(ROOT, "validation", "report.md"), "w", encoding="utf-8") as f:
    f.write("# Synthetic data validation report\n\n")
    f.write("Generated by `python validation/validate.py` from the OMOP extracts in `data/` and `data_eval/`. "
            "Synthetic values are means with a 95% interval. Targets and sources are in `validation/targets.json`.\n\n")
    f.write("| Result | Status | What | Synthetic | Target | Source |\n| --- | --- | --- | --- | --- | --- |\n")
    for t, v, se, n, diff, verdict in rows:
        src = f"[{t['source']}]({t['url']})" if t["url"] else t["source"]
        f.write(f"| {verdict} | {t['status']} | {t['what']} | {v:.1%} ± {1.96 * se:.1%} (n={n:,}) | "
                f"{t['target']:.1%} ± {t['tolerance']:.1%} | {src} |\n")
    f.write("\n**Status:** verified = checked against the publication or its abstract; provisional = seen only in a secondary source, verify before relying on it; "
            "assumption = no published figure found, chosen by the PoC team and not scored.\n\n")
    f.write("**Notes**\n\n")
    for t, *_ in rows:
        if t["note"]:
            f.write(f"- `{t['id']}`: {t['note']}\n")
print(f"\nwrote validation/report.md; {len(failed)} verified target(s) failed" + (f": {', '.join(failed)}" if failed else ""))
sys.exit(1 if failed else 0)
